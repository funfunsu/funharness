export function createRemoteApiPlatformStrategy(
    endpoint: MonorepoRemoteEndpoint,
    deps: RemoteApiPlatformStrategyDeps,
): RemoteApiPlatformStrategy | null {
    if (endpoint.platform === 'github') {
        return {
            testToken: async (token) => testGithubToken(endpoint, token, deps),
            createOrUpdate: async (task, sourceBranch, targetBranch, token) =>
                createOrUpdateGithubPullByToken(endpoint, task, sourceBranch, targetBranch, token, deps),
            queryStatus: async (item, token) => queryGithubPullStatusByToken(endpoint, item, token, deps),
        };
    }

    if (endpoint.platform === 'gitlab') {
        return {
            testToken: async (token) => testGitlabToken(endpoint, token, deps),
            createOrUpdate: async (task, sourceBranch, targetBranch, token) =>
                createOrUpdateGitlabMergeByToken(endpoint, task, sourceBranch, targetBranch, token, deps),
            queryStatus: async (item, token) => queryGitlabMergeStatusByToken(endpoint, item, token, deps),
        };
    }

    return null;
}
